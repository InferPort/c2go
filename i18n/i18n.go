func Init(lang string) {
	if lang == "" {
		// Detect from system
		langEnv := os.Getenv("LANG")
		if langEnv == "" {
			langEnv = os.Getenv("LC_ALL")
		}
		if strings.HasPrefix(strings.ToLower(langEnv), "es") {
			CurrentLang = "es"
		} else {
			CurrentLang = "en"
		}
	} else {
		if lang == "es" || lang == "en" {
			CurrentLang = lang
		}
	}
}

func T(key string, args ...interface{}) string {
	langMap, exists := translations[CurrentLang]
	if !exists {
		langMap = translations["en"]
	}
	val, exists := langMap[key]
	if !exists {
		// Fallback to English
		val = translations["en"][key]
	}
	if len(args) > 0 {
		return fmt.Sprintf(val, args...)
	}
	return val
}
